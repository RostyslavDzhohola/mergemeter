"""Write EVAL.md: TabPFN vs logistic regression on real repos.

    GITHUB_TOKEN=... python scripts/eval.py --refresh   # re-fetch and re-snapshot
    python scripts/eval.py                              # reuse data/snapshots
"""

from __future__ import annotations

import argparse
import json
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402

from mergemeter import github  # noqa: E402
from mergemeter.features import build_dataset  # noqa: E402
from mergemeter.model import N_ESTIMATORS, cross_validate, time_split_auc, to_frame  # noqa: E402

REPOS = [
    ("huggingface/transformers", "large"),
    ("psf/requests", "large, mostly-unmerged"),
    ("encode/httpx", "medium"),
    ("fastapi/fastapi", "large, maintainer-driven"),
    ("pallets/flask", "medium, mostly-unmerged"),
    ("fastapi/sqlmodel", "small"),
    ("gradio-app/gradio", "large, mostly-merged"),
    ("firstcontributions/first-contributions", "Hacktoberfest practice repo"),
]


def load(repo: str, refresh: bool) -> dict:
    snap = github._snapshot_path(repo)
    if snap.exists() and not refresh:
        return json.loads(snap.read_text())
    data = github.fetch_prs(repo, use_cache=False)
    github.SNAPSHOT_DIR.mkdir(parents=True, exist_ok=True)
    snap.write_text(json.dumps(data))
    return data


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--refresh", action="store_true")
    parser.add_argument("--out", default=str(ROOT / "EVAL.md"))
    args = parser.parse_args()

    rows = []
    for repo, kind in REPOS:
        t0 = time.time()
        data = load(repo, args.refresh)
        X_rows, y, closed, _, opened = build_dataset(data["prs"])
        X = to_frame(X_rows)
        cv = cross_validate(X, y)
        ts = time_split_auc(X, y, [p["created_at"] for p in closed])
        rows.append({
            "repo": repo, "kind": kind, "fetched_at": data["fetched_at"], "mode": data["mode"],
            "n": len(y), "merged": int(np.sum(y)), "open": len(opened), "cv": cv, "ts": ts,
            "seconds": round(time.time() - t0, 1),
        })
        print(f"{repo}: TabPFN {cv['tabpfn'][0]:.3f} vs LR {cv['logreg'][0]:.3f} "
              f"(time split {ts.get('tabpfn', float('nan')):.3f} vs {ts.get('logreg', float('nan')):.3f})", flush=True)

    Path(args.out).write_text(render(rows))
    print(f"wrote {args.out}")


def render(rows: list[dict]) -> str:
    wins = sum(r["cv"]["tabpfn"][0] > r["cv"]["logreg"][0] for r in rows)
    mean_t = np.mean([r["cv"]["tabpfn"][0] for r in rows])
    mean_l = np.mean([r["cv"]["logreg"][0] for r in rows])
    timed = [r for r in rows if r["ts"]]
    ts_wins = sum(r["ts"]["tabpfn"] > r["ts"]["logreg"] for r in timed)
    ts_ties = sum(r["ts"]["tabpfn"] == r["ts"]["logreg"] for r in timed)
    lines = [
        "# EVAL: TabPFN vs logistic regression",
        "",
        "Generated by `python scripts/eval.py` from the snapshots in `data/snapshots/` "
        f"(fetched {min(r['fetched_at'] for r in rows)[:10]}). Re-run it to reproduce every number below.",
        "",
        f"**TabPFN beats the baseline on {wins} of {len(rows)} repos; mean 5-fold ROC-AUC "
        f"{mean_t:.3f} vs {mean_l:.3f}.** On the harder time split (train on old PRs, test on new) it wins "
        f"{ts_wins}, ties {ts_ties} and loses {len(timed) - ts_wins - ts_ties} of {len(timed)}: "
        "repos change their habits over time, and neither model sees that coming.",
        "",
        "## Setup",
        "",
        "- Data: the 300 most recent closed PRs per repo (GitHub GraphQL). Label = merged (1) vs closed without merging (0).",
        "- Features: the 20 leakage-safe features in `mergemeter/features.py` (size, files, tests/docs, author history "
        "counted from *earlier* PRs only, first-24 h comments and reviews, linked issue, title/body, topic labels).",
        f"- TabPFN: open-weight TabPFN v2 classifier checkpoint, local CPU, `n_estimators={N_ESTIMATORS}`, no tuning, "
        "no training loop (in-context learning).",
        "- Baseline: median impute, log1p, standardise, `LogisticRegression(class_weight='balanced')`.",
        "- **5-fold CV**: stratified, shuffled, seed 0, both models on identical folds (mean ± std).",
        "- **Time split**: train on the oldest 80 % of PRs, test on the newest 20 %: the \"predict the future\" check.",
        "",
        "## Results",
        "",
        "| Repo | Kind | Closed PRs | Merged | TabPFN CV AUC | LogReg CV AUC | Δ | TabPFN time-split | LogReg time-split |",
        "|---|---|---:|---:|---:|---:|---:|---:|---:|",
    ]
    for r in rows:
        t, l = r["cv"]["tabpfn"], r["cv"]["logreg"]
        ts_t = f"{r['ts']['tabpfn']:.3f}" if r["ts"] else "n/a"
        ts_l = f"{r['ts']['logreg']:.3f}" if r["ts"] else "n/a"
        cv_t, cv_l = f"{t[0]:.3f}", f"{l[0]:.3f}"
        if t[0] > l[0]:
            cv_t = f"**{cv_t}**"
        elif l[0] > t[0]:
            cv_l = f"**{cv_l}**"
        lines.append(
            f"| [{r['repo']}](https://github.com/{r['repo']}) | {r['kind']} | {r['n']} | {r['merged']} "
            f"| {cv_t} ± {t[1]:.3f} | {cv_l} ± {l[1]:.3f} | {t[0] - l[0]:+.3f} | {ts_t} | {ts_l} |"
        )
    lines += [
        "",
        "## Caveats",
        "",
        "- 300 PRs is a small sample; fold-to-fold spread (± std) is a few AUC points, so small gaps are noise.",
        "- `additions`, `deletions` and `changed_files` are the PR's final size, which can drift from its size at "
        "open time. Every other feature is known at open time or within 24 h.",
        "- Repos where maintainers and bots drive nearly every merge (fastapi) are easy for both models: "
        "\"who opened it\" carries most of the signal.",
        "- TabPFN 2.5+ checkpoints are licence-gated and non-commercial; this eval uses the open v2 checkpoint "
        "that the app ships with.",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    main()
